/**
 * Generates supabase/seed.sql from the content layer (src/data), so Postgres mirrors exactly
 * what is versioned in git. Run: npm run seed:sql
 */
import fs from "node:fs";
import path from "node:path";
import { CURRICULA } from "../src/data/curricula";
import { SUBJECTS, WORLDS } from "../src/data/worlds";
import { TOPICS } from "../src/data/topics";
import { ACHIEVEMENTS } from "../src/data/achievements";
import { ITEMS } from "../src/data/items";
import { LESSONS as EARLY } from "../src/data/lessons/early";
import { LESSONS as MATH } from "../src/data/lessons/math";
import { LESSONS as READING } from "../src/data/lessons/reading";
import { LESSONS as SCIENCE } from "../src/data/lessons/science";
import { LESSONS as LANGUAGES } from "../src/data/lessons/languages";
import { LESSONS as TECH } from "../src/data/lessons/tech";

const q = (v: unknown): string => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "number") return String(v);
  if (typeof v === "boolean") return v ? "true" : "false";
  if (Array.isArray(v) && v.every((x) => typeof x === "string")) return `array[${v.map((x) => q(x)).join(",")}]::text[]`;
  if (typeof v === "object") return `${q(JSON.stringify(v))}::jsonb`;
  return `'${String(v).replace(/'/g, "''")}'`;
};
const row = (vals: unknown[]) => `(${vals.map(q).join(", ")})`;
const insert = (table: string, cols: string[], rows: unknown[][]) =>
  rows.length ? `insert into public.${table} (${cols.join(", ")}) values\n  ${rows.map(row).join(",\n  ")}\non conflict (id) do nothing;\n` : "";

const lessons = [...EARLY, ...MATH, ...READING, ...SCIENCE, ...LANGUAGES, ...TECH];
let sql = "-- Generated by scripts/generate-seed.ts - do not edit by hand.\n\n";
sql += insert("curricula", ["id", "country_code", "name", "language", "version", "status", "source", "official"], CURRICULA.map((c) => [c.id, c.countryCode, c.name, c.language, c.version, c.status, c.source, c.official]));
sql += insert("subjects", ["id", "name", "slug", "description"], SUBJECTS.map((s) => [s.slug, s.name, s.slug, s.description]));
sql += insert("worlds", ["id", "name", "slug", "description", "theme", "unlock_requirements"], WORLDS.map((w) => [w.slug, w.name, w.slug, w.description, { palette: w.palette, emoji: w.emoji, guide: w.guide, mapPos: w.mapPos }, { topics: w.unlockTopics, grade: w.unlockGrade ?? null }]));
sql += insert("topics", ["id", "subject_id", "grade_from", "grade_to", "title", "description", "prerequisites"], TOPICS.map((t) => [t.id, t.subject, t.grades[0], t.grades[1], t.title, t.description, t.prerequisites]));
sql += insert("lessons", ["id", "topic_id", "title", "content", "difficulty", "duration", "objectives", "status"], lessons.map((l) => {
  const { practice, check, ...rest } = l;
  void practice; void check;
  return [l.id, l.topicId, l.title, rest, l.difficulty, l.durationMin, { objective: l.objective, masteryScore: l.masteryScore }, l.status];
}));
sql += insert("questions", ["id", "lesson_id", "type", "question_data", "difficulty", "explanation"], lessons.flatMap((l) => [...l.practice.map((x) => ({ x, role: "practice" })), ...l.check.map((x) => ({ x, role: "check" }))].map(({ x, role }) => [x.id, l.id, x.type, { ...x, role }, x.difficulty, x.explanation])));
sql += insert("achievements", ["id", "name", "description", "icon", "requirement"], ACHIEVEMENTS.map((a) => [a.id, a.name, a.description, a.icon, { ...a.requirement, reward: a.reward }]));
sql += insert("game_items", ["id", "name", "type", "rarity", "price", "asset_path"], ITEMS.map((i) => [i.id, i.name, i.type, i.rarity, i.price, i.art]));
// grade_subjects: which subjects the core framework offers per grade (derived from topic bands)
const gs: unknown[][] = [];
for (let g = -1; g <= 11; g++) for (const s of SUBJECTS) if (TOPICS.some((t) => t.subject === s.slug && t.grades[0] <= g && t.grades[1] >= g)) gs.push([g, s.slug, "eduworld-core-v1"]);
sql += `insert into public.grade_subjects (grade, subject_id, curriculum_id) values\n  ${gs.map(row).join(",\n  ")}\non conflict do nothing;\n`;

const out = path.resolve("supabase/seed.sql");
fs.writeFileSync(out, sql);
console.log(`Wrote ${out}: ${lessons.length} lessons, ${lessons.reduce((n, l) => n + l.practice.length + l.check.length, 0)} questions`);
