import type { GeneratedSet, GradeRange, Lesson, LText, MiniGameId, Question, Visual } from "@/types/content";

/**
 * Numberia (mathematics) lessons: one lesson per math topic in src/data/topics.ts.
 * Ids: lesson `<topicId>.l1`, practice `<lessonId>.pN`, check `<lessonId>.cN` (assigned by `lesson()`).
 */

type Difficulty = 1 | 2 | 3 | 4 | 5;
/** A question without id; difficulty defaults to the lesson difficulty. */
type QIn = Question extends infer U ? (U extends Question ? Omit<U, "id" | "difficulty"> & { difficulty?: Difficulty } : never) : never;

const T = (en: string, ru: string): LText => ({ en, ru });

interface Spec {
  topicId: string;
  grades: GradeRange;
  difficulty: Difficulty;
  durationMin: number;
  title: LText;
  subtopic: LText;
  objective: LText;
  intro: LText;
  explanation: LText[];
  example: Visual;
  practice: QIn[];
  generated?: GeneratedSet[];
  game?: MiniGameId;
  check: QIn[];
  reviewTips: LText;
}

function lesson(s: Spec): Lesson {
  const id = `${s.topicId}.l1`;
  // Young learners (grades 1-2) get prompts read aloud.
  const audio = s.grades[0] <= 2;
  const fix = (prefix: string) => (q: QIn, i: number): Question =>
    ({ ...(audio ? { audio: true } : {}), ...q, difficulty: q.difficulty ?? s.difficulty, id: `${id}.${prefix}${i + 1}` }) as Question;
  return {
    id,
    topicId: s.topicId,
    title: s.title,
    subtopic: s.subtopic,
    objective: s.objective,
    ageRange: [s.grades[0] + 5, Math.min(s.grades[1] + 8, 18)],
    grades: s.grades,
    difficulty: s.difficulty,
    durationMin: s.durationMin,
    character: "oli",
    intro: s.intro,
    explanation: s.explanation,
    example: s.example,
    practice: s.practice.map(fix("p")),
    ...(s.generated ? { generated: s.generated } : {}),
    ...(s.game ? { game: s.game } : {}),
    check: s.check.map(fix("c")),
    masteryScore: 0.8,
    reviewTips: s.reviewTips,
    status: "reviewed",
  };
}

