/** Traceable ellipse (closed polyline) in 0..100 coordinates. */
function ellipse(rx = 35, ry = 35, cx = 50, cy = 50, n = 12): [number, number][] {
  const pts: [number, number][] = [];
  for (let i = 0; i <= n; i++) {
    const a = (i / n) * 2 * Math.PI - Math.PI / 2;
    pts.push([Math.round((cx + rx * Math.cos(a)) * 10) / 10, Math.round((cy + ry * Math.sin(a)) * 10) / 10]);
  }
  return pts;
}

